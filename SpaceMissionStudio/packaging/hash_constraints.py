"""Write ``constraints-hashes.txt``: every pin of ``constraints.txt`` with
the SHA-256 of each file PyPI publishes for it.

The installers build with ``pip install --require-hashes`` against that
file, so a package file that is not byte for byte the one recorded here
stops the build, and so does any package that is not pinned at all.
``constraints.txt`` stays the readable list CI and developers install
with (an editable install cannot be hash-checked).

The digests are PyPI's own (its JSON API). Only the files a Python 3.14
can install are kept: wheels for CPython 3.14, ``abi3`` wheels for an
earlier CPython 3, pure-Python wheels and the source archive. Before
writing, the script follows every requirement of Basilisk (``bsk[all]``)
and of SpaceMissionStudio (``[gui]``) on Linux x86_64 and Windows x64 and
stops if one is not pinned, or has no wheel for one of them.

Run it after changing ``constraints.txt``::

    python packaging/hash_constraints.py

``--check`` compares the two files without the network: the same
packages at the same versions, each with at least one digest.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
import urllib.request
from pathlib import Path

_PACKAGING = Path(__file__).resolve().parent
CONSTRAINTS = _PACKAGING / "constraints.txt"
HASHED = _PACKAGING / "constraints-hashes.txt"
PYPI = "https://pypi.org/pypi/{name}/{version}/json"

#: The platforms the installers are built for, as pip evaluates markers.
PLATFORMS = {
    "linux": {"sys_platform": "linux", "platform_system": "Linux", "platform_machine": "x86_64",
              "os_name": "posix", "wheel": re.compile(r"(manylinux|linux)_?.*x86_64|^any$")},
    "windows": {"sys_platform": "win32", "platform_system": "Windows", "platform_machine": "AMD64",
                "os_name": "nt", "wheel": re.compile(r"^win_amd64$|^any$")},
}
PYTHON = (3, 14)

HEADER = """\
# Generated by packaging/hash_constraints.py from constraints.txt: do not
# edit, run the script. Each pin with the SHA-256 of every file PyPI
# publishes for it that Python 3.14 can install. bundle_python.py builds
# the .deb's and the setup program's Python with
# `pip install --require-hashes -c constraints-hashes.txt`, so a file that
# differs from the one recorded here, or a package not pinned, stops the
# build (packaging/README.md, "Pinned and hash-checked dependencies").
"""


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_pins(path: Path) -> dict[str, tuple[str, str, list[str]]]:
    """``{normalised name: (name as written, version, [sha256, ...])}``
    for a constraints file, hashed or not."""
    pins = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        requirement, *options = line.split()
        name, _, version = requirement.partition("==")
        if not version:
            raise ValueError(f"{path.name}: not an exact pin: {line!r}")
        digests = [option.removeprefix("--hash=sha256:") for option in options if option.startswith("--hash=sha256:")]
        pins[normalise(name)] = (name, version, digests)
    return pins


def installable(filename: str) -> bool:
    """A file a CPython 3.14 can install: the source archive, a
    pure-Python wheel, a CPython 3.14 wheel or an ``abi3`` one."""
    if not filename.endswith(".whl"):
        return filename.endswith((".tar.gz", ".zip"))
    python_tags, abi_tags = filename[:-4].split("-")[-3:-1]
    for python_tag in python_tags.split("."):
        if python_tag.startswith("py3") or python_tag == "py2.py3":
            return True
        if python_tag == "cp314" and "cp314t" not in abi_tags:
            return True
        if python_tag.startswith("cp3") and "abi3" in abi_tags and int(python_tag[3:]) <= PYTHON[1]:
            return True
    return False


def has_wheel_for(files: list[str], platform: str) -> bool:
    pattern = PLATFORMS[platform]["wheel"]
    return any(name.endswith(".whl") and any(pattern.search(tag) for tag in name[:-4].split("-")[-1].split("."))
               for name in files if installable(name))


def fetch(name: str, version: str) -> dict:
    with urllib.request.urlopen(PYPI.format(name=name, version=version), timeout=60) as response:  # noqa: S310
        return json.load(response)


def unpinned(pins: dict, releases: dict, roots: list[str]) -> list[str]:
    """Every requirement reached from ``roots`` on each platform that
    ``pins`` does not pin; empty when the set is closed."""
    from packaging.requirements import Requirement

    missing = []
    for platform, markers in PLATFORMS.items():
        environment = {key: value for key, value in markers.items() if key != "wheel"}
        environment.update(python_version="3.14", python_full_version="3.14.0", implementation_name="cpython",
                           platform_python_implementation="CPython")
        queue = [Requirement(root) for root in roots]
        seen = set()
        while queue:
            requirement = queue.pop()
            name = normalise(requirement.name)
            key = (name, tuple(sorted(requirement.extras)))
            if key in seen:
                continue
            seen.add(key)
            if name == "spacemissionstudio":
                requires = releases["spacemissionstudio"]
            elif name not in pins:
                missing.append(f"{requirement.name} ({platform})")
                continue
            else:
                requires = releases[name]["info"]["requires_dist"] or []
            for text in requires:
                child = Requirement(text)
                if child.marker is None or any(child.marker.evaluate({**environment, "extra": extra})
                                               for extra in (requirement.extras or {""})):
                    queue.append(child)
    return sorted(set(missing))


def project_requirements(pyproject: Path) -> list[str]:
    project = tomllib.loads(pyproject.read_text(encoding="utf-8"))["project"]
    return project["dependencies"] + [f"{text}; extra == 'gui'" for text in project["optional-dependencies"]["gui"]]


def generate(constraints: Path = CONSTRAINTS, out: Path = HASHED, basilisk: str = "bsk[all]") -> int:
    pins = read_pins(constraints)
    releases, lines, problems = {}, [], []
    for key, (name, version, _) in sorted(pins.items()):
        release = fetch(name, version)
        releases[key] = release
        files = sorted(entry["filename"] for entry in release["urls"])
        digests = sorted(entry["digests"]["sha256"] for entry in release["urls"] if installable(entry["filename"]))
        if not digests:
            problems.append(f"{name}=={version}: no file for Python 3.14")
        for platform in PLATFORMS:
            if not has_wheel_for(files, platform):
                problems.append(f"{name}=={version}: no wheel for {platform} (pip would build the source)")
        lines.append(f"{name}=={version} " + " ".join(f"--hash=sha256:{digest}" for digest in digests))
        print(f"{name}=={version}: {len(digests)} files", flush=True)
    releases["spacemissionstudio"] = project_requirements(_PACKAGING.parent / "pyproject.toml")
    problems += [f"not pinned: {name}" for name in unpinned(pins, releases, [basilisk, "spacemissionstudio[gui]"])]
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    out.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out} ({len(lines)} packages)")
    return 0


def check(constraints: Path = CONSTRAINTS, hashed: Path = HASHED) -> list[str]:
    """The differences between the two files; empty when they agree."""
    pins, recorded = read_pins(constraints), read_pins(hashed)
    problems = [f"{pins[k][0]}=={pins[k][1]} has no digests in {hashed.name}" for k in pins if k not in recorded]
    problems += [f"{recorded[k][0]} is in {hashed.name} but not in {constraints.name}" for k in recorded if k not in pins]
    for key in pins.keys() & recorded.keys():
        if pins[key][1] != recorded[key][1]:
            problems.append(f"{pins[key][0]}: {pins[key][1]} in {constraints.name}, {recorded[key][1]} in {hashed.name}")
        if not recorded[key][2] or any(not re.fullmatch(r"[0-9a-f]{64}", d) for d in recorded[key][2]):
            problems.append(f"{pins[key][0]}: no valid SHA-256 in {hashed.name}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="compare the two files without the network")
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        print("\n".join(problems) or f"{HASHED.name} matches {CONSTRAINTS.name}")
        return 1 if problems else 0
    return generate()


if __name__ == "__main__":
    sys.exit(main())
